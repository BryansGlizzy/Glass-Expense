import db from './db.js';
import { sendActivityDigestEmail, sendSubscriptionReminderEmail, sendReportEmail, type ActivityDigest } from './email.js';
import { unwrapForServer, decryptEnvelopeServer, serverCryptoAvailable } from './server-crypto.js';
import { buildReport, isSnapshot, FREQUENCY_DAYS } from './report.js';
import type { Server } from 'socket.io';
import { getFirebaseMessaging } from './push.js';

// Schedulers. Because expense content is end-to-end encrypted, the server cannot create recurring expenses or write
// figures into emails: it only sends content-free activity digests and generic renewal reminders. Recurring
// expenses are generated by the user's own client when the app is opened (see src/e2ee/subscriptions.ts).

export const calculateNextRun = (frequency: string): string | null => {
  if (frequency === 'NONE') return null;
  const now = new Date();
  if (frequency === 'WEEKLY') now.setDate(now.getDate() + 7);
  else if (frequency === 'BIWEEKLY') now.setDate(now.getDate() + 14);
  else if (frequency === 'MONTHLY') now.setMonth(now.getMonth() + 1);
  return now.toISOString();
};

export const generateActivityDigest = (userId: string, frequency: string): ActivityDigest => {
  const now = new Date();
  const start = new Date();
  if (frequency === 'BIWEEKLY') start.setDate(now.getDate() - 14);
  else if (frequency === 'MONTHLY') start.setMonth(now.getMonth() - 1);
  else start.setDate(now.getDate() - 7);

  const rows = db.prepare(`
    SELECT e.job_id, COUNT(*) AS n FROM expenses e
    JOIN jobs j ON j.id = e.job_id
    LEFT JOIN job_users ju ON ju.job_id = j.id AND ju.user_id = ? AND COALESCE(ju.status, 'active') = 'active'
    WHERE (j.created_by = ? OR ju.user_id IS NOT NULL) AND j.is_archived = 0 AND date(e.created_at) >= date(?)
    GROUP BY e.job_id`).all(userId, userId, start.toISOString().split('T')[0]) as any[];

  return {
    timeWindowStart: start.toLocaleDateString(),
    timeWindowEnd: now.toLocaleDateString(),
    jobCount: rows.length,
    entryCount: rows.reduce((sum, r) => sum + r.n, 0),
  };
};

const FREQUENCY_LABEL: Record<string, string> = { WEEKLY: 'Weekly', BIWEEKLY: 'Bi-weekly', MONTHLY: 'Monthly' };

/**
 * Sends the figure-bearing report if (and only if) the user opted in and has uploaded a snapshot. The snapshot is decrypted in
 * memory with the user's report key, turned into totals/winners/loss-leaders, mailed, and discarded.
 * Returns false when the caller should fall back to the content-free activity digest.
 */
export const sendReportForUser = async (userId: string, frequency: string): Promise<boolean> => {
  if (!serverCryptoAvailable()) return false;
  const user = db.prepare('SELECT username, email, server_report_key FROM users WHERE id = ?').get(userId) as any;
  const snap = db.prepare('SELECT enc FROM report_snapshots WHERE user_id = ?').get(userId) as any;
  if (!user?.email || !user.server_report_key || !snap) return false;
  try {
    const key = unwrapForServer(user.server_report_key, 'server-report-key');
    const snapshot = decryptEnvelopeServer<unknown>(key, snap.enc, `report-snapshot|${userId}`);
    if (!isSnapshot(snapshot)) return false;
    const days = FREQUENCY_DAYS[frequency] ?? 7;
    await sendReportEmail(user.email, user.username, buildReport(snapshot, days), FREQUENCY_LABEL[frequency] ?? 'Weekly');
    return true;
  } catch (e) {
    console.error('Could not build report from snapshot:', (e as Error).message);
    return false;
  }
};

export const runReportSweep = async () => {
  try {
    const nowIso = new Date().toISOString();
    const due = db.prepare("SELECT * FROM report_settings WHERE frequency != 'NONE' AND next_run_at <= ?").all(nowIso) as any[];
    for (const settings of due) {
      const user = db.prepare('SELECT id, username, email FROM users WHERE id = ?').get(settings.user_id) as any;
      if (user?.email) {
        const sentWithFigures = await sendReportForUser(user.id, settings.frequency);
        const digest = generateActivityDigest(user.id, settings.frequency);
        if (!sentWithFigures && digest.entryCount > 0) void sendActivityDigestEmail(user.email, user.username, digest);
        db.prepare('UPDATE report_settings SET last_run_at = ?, next_run_at = ? WHERE user_id = ?').run(nowIso, calculateNextRun(settings.frequency), user.id);
      }
    }
  } catch (err) {
    console.error('Report scheduler error:', err);
  }
};

const push = async (token: string | null | undefined, title: string, body: string) => {
  if (!token) return;
  try {
    const messaging = getFirebaseMessaging();
    if (messaging) await messaging.send({ token, notification: { title, body } });
  } catch (e) {
    console.error('Push error:', (e as Error).message);
  }
};

export const runReminderSweep = (io: Server) => {
  try {
    const subs = db.prepare('SELECT * FROM subscriptions WHERE is_active = 1 AND next_generation_date IS NOT NULL').all() as any[];
    for (const sub of subs) {
      const user = db.prepare('SELECT username, email, device_token FROM users WHERE id = ?').get(sub.user_id) as any;
      if (!user) continue;
      const days = (new Date(sub.next_generation_date).getTime() - Date.now()) / 86400000;

      const windows: Array<[number, number, string, string, number]> = [
        [7, 2, 'remind_7_days_before', 'remind_7_sent', 7],
        [2, 1, 'remind_2_days_before', 'remind_2_sent', 2],
        [1, 0, 'remind_1_day_before', 'remind_1_sent', 1],
      ];
      for (const [upper, lower, wantCol, sentCol, daysBefore] of windows) {
        if (days <= upper && days > lower && sub[wantCol] === 1 && sub[sentCol] === 0) {
          if (user.email) void sendSubscriptionReminderEmail(user.email, user.username, sub.next_generation_date, daysBefore);
          void push(user.device_token, 'Subscription reminder', `A subscription is due in ${daysBefore} day${daysBefore === 1 ? '' : 's'}.`);
          io.to(sub.job_id).emit('subscription_reminder', { id: sub.id, next_generation_date: sub.next_generation_date, daysBefore });
          db.prepare(`UPDATE subscriptions SET ${sentCol} = 1 WHERE id = ?`).run(sub.id);
        }
      }
    }
  } catch (err) {
    console.error('Reminder scheduler error:', err);
  }
};
