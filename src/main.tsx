import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import App from './App.tsx';
import './index.css';

import { Capacitor } from '@capacitor/core';

import { CapacitorUpdater } from '@capgo/capacitor-updater';

// Intercept fetch calls on native platforms to point to the live server
const originalFetch = window.fetch;
window.fetch = async function(...args) {
  let [resource, config] = args;
  if (typeof resource === 'string' && (resource.startsWith('/api') || resource.startsWith('/updates'))) {
    if (Capacitor.isNativePlatform()) {
      resource = 'https://expenses.futurelabz.dev' + resource;
    }
  }
  return originalFetch(resource, config);
};

// Encrypted API layer: pages keep using /api/... while data is decrypted/encrypted in the browser.
import { installE2eeRouter } from './e2ee/router';
installE2eeRouter();

if (Capacitor.isNativePlatform()) {
  CapacitorUpdater.notifyAppReady().catch(console.error);
}

// Explicitly register the service worker generated by vite-plugin-pwa.
// This is the most reliable trigger for the Android Chrome "Install App" prompt.
import { registerSW } from 'virtual:pwa-register';
registerSW({
  // Silently update in the background — no user interruption
  immediate: true,
  onRegisteredSW(swUrl, registration) {
    if (!registration) return;
    // Poll every 60 minutes for a new service worker version
    setInterval(async () => {
      if (!(!registration.installing && navigator)) return;
      if ('connection' in navigator && !navigator.onLine) return;
      const resp = await fetch(swUrl, { cache: 'no-store', headers: { 'cache': 'no-store', 'cache-control': 'no-cache' } });
      if (resp?.status === 200) await registration.update();
    }, 60 * 60 * 1000);
  },
});

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
);
